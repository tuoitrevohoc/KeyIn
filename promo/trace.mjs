// Types every scene script through the real KeyIn controller (examples/trace.rs) and writes data.js.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..');
new Function(readFileSync(join(here, 'edl.js'), 'utf8'))();
const app = join(root, 'build/KeyIn.app/Contents');
const env = { ...process.env, KEYIN_RIME_LIB: join(app, 'Frameworks/librime.1.dylib'),
  KEYIN_RIME_SHARED: join(app, 'Resources/rime'), KEYIN_MEANINGS: join(app, 'Resources/chinese-meanings.json') };
execFileSync('cargo', ['build', '-q', '--release', '--example', 'trace'], { cwd: root, stdio: 'inherit' });
const TRACE = {};
for (const [id, s] of Object.entries(globalThis.EDL.scenes)) {
  const out = execFileSync(join(root, 'target/release/examples/trace'), [s.script.replaceAll('|', '')],
    { env: { ...env, KEYIN_ML: String(s.ml) }, encoding: 'utf8' });
  TRACE[id] = out.trim().split('\n').map(l => JSON.parse(l));
  console.log(id.padEnd(6), JSON.stringify(TRACE[id].at(-1).doc + TRACE[id].at(-1).pre));
}
writeFileSync(join(here, 'data.js'), '// Generated by trace.mjs from the real KeyIn engine. Do not edit.\nglobalThis.TRACE = ' + JSON.stringify(TRACE) + ';\n');
