#!/usr/bin/env python3
"""Build data/rime/keyin-words.tsv: frequent simplified words missing from
pinyin_simp, so whole words such as 越南语 beat unrelated per-syllable picks.

Sources (both MIT, see data/README.chinese-words.md):
  jieba dict.txt            fxsjy/jieba 67fa2e36e72f69d9134b8a1037b83fbb070b9775
  large_pinyin.txt          mozillazg/phrase-pinyin-data 4afa3226ce53c9138b939e83c3bb294dbe0da511
Usage: python3 scripts/import-chinese-words.py /path/to/dict.txt /path/to/large_pinyin.txt
"""
from collections import defaultdict
from pathlib import Path
import sys
import unicodedata

root = Path(__file__).resolve().parent.parent
jieba_path, pinyin_path = map(Path, sys.argv[1:3])

# Known words, single-character readings and valid syllables from pinyin_simp.
known = set()
char_readings = defaultdict(dict)
syllables = set()
for line in (root / 'data/pinyin_simp.dict.yaml').read_text().splitlines():
    fields = line.split('\t')
    if len(fields) < 3 or not fields[2].isdigit():
        continue
    word, reading, weight = fields[0], fields[1], int(fields[2])
    known.add(word)
    syllables.update(reading.split())
    if len(word) == 1:
        char_readings[word][reading] = char_readings[word].get(reading, 0) + weight


def toneless(syllable):
    syllable = syllable.replace('ü', 'v').replace('Ü', 'v')
    syllable = ''.join(c for c in unicodedata.normalize('NFD', syllable)
                       if not unicodedata.combining(c)).lower()
    # pinyin_simp spells lüe/nüe as lue/nue and lü/nü as lv/nv.
    return {'lve': 'lue', 'nve': 'nue'}.get(syllable, syllable)


phrase_readings = {}
for line in pinyin_path.read_text().splitlines():
    if line.startswith('#') or ': ' not in line:
        continue
    word, reading = line.split(': ', 1)
    phrase_readings[word] = ' '.join(toneless(s) for s in reading.split())


def dominant(char):
    """The reading of a character that carries at least 90% of its weight."""
    readings = char_readings.get(char)
    if not readings:
        return None
    total = sum(readings.values())
    reading, weight = max(readings.items(), key=lambda item: item[1])
    return reading if total and weight / total >= 0.9 else None


# Weights: jieba counts run about half the scale of pinyin_simp's phrase
# weights (median ratio e^0.54 for two-character words), so double them.
SCALE = 2
rows = []
for line in jieba_path.read_text().splitlines():
    word, count, _ = line.split(' ')
    count = int(count)
    if len(word) < 2 or word in known:
        continue
    if not all('一' <= c <= '鿿' for c in word):
        continue
    reading = phrase_readings.get(word)
    if reading is None and count >= 5:
        # Without a curated reading, accept only unambiguous characters.
        parts = [dominant(c) for c in word]
        reading = None if None in parts else ' '.join(parts)
    if reading is None:
        continue
    parts = reading.split()
    if len(parts) != len(word) or not set(parts) <= syllables:
        continue
    rows.append((word, reading, count * SCALE))

rows.sort(key=lambda row: (row[1].replace(' ', ''), -row[2], row[0]))
output = root / 'data/rime/keyin-words.tsv'
with output.open('w') as file:
    file.write('# Generated by scripts/import-chinese-words.py from jieba + phrase-pinyin-data (MIT).\n')
    for word, reading, weight in rows:
        file.write(f'{word}\t{reading}\t{weight}\n')
print(f'{len(rows)} entries written to {output}')
